/**
 * server/api/helpers/ai/generate-completion.js
 * Multi-provider decoupled AI client (Gemini / OpenAI / OpenRouter).
 */

module.exports = {
  inputs: {
    systemPrompt: {
      type: 'string',
      defaultsTo: 'You are an intelligent assistant in Trelle project management.',
    },
    userPrompt: {
      type: 'string',
      required: true,
    },
    jsonMode: {
      type: 'boolean',
      defaultsTo: false,
    },
  },

  exits: {
    success: {
      description: 'Completion successfully generated.',
    },
  },

  async fn(inputs) {
    const apiKey =
      process.env.AI_API_KEY ||
      process.env.GEMINI_API_KEY ||
      process.env.OPENAI_API_KEY ||
      process.env.OPENROUTER_API_KEY;

    const provider = (process.env.AI_PROVIDER || (process.env.GEMINI_API_KEY ? 'gemini' : 'openai')).toLowerCase();
    const model = process.env.AI_MODEL || (provider === 'gemini' ? 'gemini-2.0-flash' : 'gpt-4o-mini');

    if (!apiKey) {
      sails.log.warn('AI API key not provided; returning rule-based mock completion.');
      if (inputs.jsonMode) {
        return JSON.stringify({
          summary: 'Executive Summary (Mock AI): The team reviewed project scope and established deliverables.',
          actionItems: ['Review architecture', 'Implement database migrations', 'Test WebSockets'],
          refinedDescription: `### Context\n${inputs.userPrompt}\n\n### Acceptance Criteria\n- [ ] Functional parity verified\n- [ ] Tests passing`,
        });
      }
      return `### Summary & Recommendations\nBased on the analysis:\n- Key objectives have been identified.\n- Prioritize high-impact deliverables.\n\n_Generated by Trelle AI Assistant._`;
    }

    try {
      if (provider === 'gemini') {
        const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
        const response = await fetch(url, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            contents: [
              {
                role: 'user',
                parts: [{ text: `${inputs.systemPrompt}\n\nUser Request:\n${inputs.userPrompt}` }],
              },
            ],
            generationConfig: {
              responseMimeType: inputs.jsonMode ? 'application/json' : 'text/plain',
              temperature: 0.2,
            },
          }),
        });

        if (!response.ok) {
          const errText = await response.text();
          throw new Error(`Gemini API error ${response.status}: ${errText}`);
        }

        const data = await response.json();
        const candidate = data.candidates?.[0]?.content?.parts?.[0]?.text;
        return candidate || '';
      }

      // OpenAI or OpenRouter-compatible endpoint
      const baseUrl =
        process.env.AI_BASE_URL ||
        (provider === 'openrouter' ? 'https://openrouter.ai/api/v1' : 'https://api.openai.com/v1');

      const response = await fetch(`${baseUrl}/chat/completions`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${apiKey}`,
        },
        body: JSON.stringify({
          model,
          messages: [
            { role: 'system', content: inputs.systemPrompt },
            { role: 'user', content: inputs.userPrompt },
          ],
          response_format: inputs.jsonMode ? { type: 'json_object' } : undefined,
          temperature: 0.2,
        }),
      });

      if (!response.ok) {
        const errText = await response.text();
        throw new Error(`OpenAI API error ${response.status}: ${errText}`);
      }

      const data = await response.json();
      return data.choices?.[0]?.message?.content || '';
    } catch (err) {
      sails.log.error('AI generation failure:', err);
      throw err;
    }
  },
};
